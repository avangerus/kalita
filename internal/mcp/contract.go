package mcp

import (
	"bytes"
	"encoding/json"
	"fmt"
)

// RenderContract renders the MCP tool contract straight from toolDefs — the
// closed list of tools this server actually dispatches (see the switch in
// tools.go's dispatch). `kalita mcp contract` (cmd/kalita/mcp.go) prints this
// to stdout for an operator to redirect into docs/MCP-CONTRACT-v1.md, and
// TestMcpContractMatchesCode (contract_test.go) diffs the committed file
// against this exact output on every test run.
//
// RELEASE-1.0 N8 §7.3 recorded the failure mode this closes: README claimed
// "~22 tools" while the code had 27, and the golden suite's doc claimed "20
// cases" while there were 41 — both hand-maintained counts that silently
// rotted the moment someone added a tool/case and forgot the prose. A count
// or tool name in docs/MCP-CONTRACT-v1.md can no longer disagree with the
// code by construction: either it was regenerated after the last tools.go
// change, or the CI gate fails.
//
// json.Marshal sorts map[string]any keys by Unicode code point, recursively —
// so this output is byte-for-byte deterministic across runs without this
// function doing any sorting of its own.
func RenderContract() string {
	var b bytes.Buffer
	b.WriteString("# Kalita MCP Contract v1\n\n")
	b.WriteString("Generated by `kalita mcp contract` from internal/mcp/tools.go's `toolDefs` —\n")
	b.WriteString("DO NOT EDIT BY HAND. Regenerate after any tool change:\n\n")
	b.WriteString("    kalita mcp contract > docs/MCP-CONTRACT-v1.md\n\n")
	b.WriteString("`TestMcpContractMatchesCode` (internal/mcp/contract_test.go) fails the build\n")
	b.WriteString("if this file and the code disagree — the tool count and names below are\n")
	b.WriteString("honest by construction, not hand-maintained prose.\n\n")
	fmt.Fprintf(&b, "**%d tools.**\n\n", len(toolDefs))
	for _, t := range toolDefs {
		name, _ := t["name"].(string)
		desc, _ := t["description"].(string)
		b.WriteString("## `" + name + "`\n\n")
		if desc != "" {
			b.WriteString(desc + "\n\n")
		}
		schema, _ := json.MarshalIndent(t["inputSchema"], "", "  ")
		b.WriteString("Input schema:\n\n```json\n")
		b.Write(schema)
		b.WriteString("\n```\n\n")
	}
	return b.String()
}
